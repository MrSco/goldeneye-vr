#!/usr/bin/env python3
"""
What Wreck's Mirror Mode flipped, from the player's two cartridges.

Bean (XBLA) and HD packs replace GoldenEye's own models and pictures. Mirror
Mode keeps them under their names but flipped some: the levels about x = 0
(rooms, collision, setups), 140 object models in their own x, and the stage
pictures. This lists which, so Bean can flip its own to match
(port/src/gevr_mirror.c). Names and numbers only; no cartridge bytes.

Usage
-----
    python tools/gevr_mirror_lists.py ge.z64 mirror.z64 [-o port/src/gevr_mirror_lists.inc.h]

ge.z64 is the retail USA cartridge, mirror.z64 the same with
GE_MirrorMode_patch.xdelta applied (docs/mirror-mode.md).
"""
import argparse
import struct
import sys
import zlib
from pathlib import Path

V = 0x80020D90                       # the data segment's address
FILE_TABLE = 0x252C4                 # file_resource_table, as the window holds it
IMAGE_ROWS = 0x80049300              # image rows (retail 8 bytes, Mirror Mode 4)
IMAGES = 2698
BANKS = {"retail": 0x8F7DF0, "mirror": 0x8EDA20}   # GEVR_SEG_IMAGES; docs/mirror-mode.md


def window(rom):
    return zlib.decompressobj(-15).decompress(rom[0x21992:])


def cstr(d, ptr):
    if ptr < V or ptr - V >= len(d):
        return ""
    end = d.index(b"\0", ptr - V)
    return d[ptr - V:end].decode("latin-1")


def files(rom):
    d = window(rom)
    rows = 0
    while struct.unpack_from(">I", d, FILE_TABLE + 12 * rows)[0] == rows:
        rows += 1
    out = {}
    for k in range(1, rows - 1):
        _, nptr, addr = struct.unpack_from(">III", d, FILE_TABLE + 12 * k)
        nxt = struct.unpack_from(">I", d, FILE_TABLE + 12 * (k + 1) + 8)[0]
        if nxt > addr:
            out[cstr(d, nptr)] = (addr, nxt - addr)
    return out


def content(rom, where):
    addr, size = where
    raw = rom[addr:addr + size]
    return zlib.decompressobj(-15).decompress(raw[2:]) if raw[:2] == b"\x11\x72" else raw


def images(rom, stride, bank):
    d = window(rom)
    out, at = [], 0
    for i in range(IMAGES):
        size = struct.unpack_from(">I", d, IMAGE_ROWS - V + stride * i)[0] & 0x7FFFFF
        out.append(rom[bank + at:bank + at + size])
        at += size
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("retail")
    ap.add_argument("mirror")
    ap.add_argument("-o", "--out", default=str(Path(__file__).resolve().parents[1] / "port/src/gevr_mirror_lists.inc.h"))
    a = ap.parse_args()
    retail, mirror = Path(a.retail).read_bytes(), Path(a.mirror).read_bytes()
    fr, fm = files(retail), files(mirror)
    props = []
    for name in sorted(fr):
        if name.startswith("P") and name in fm and content(retail, fr[name]) != content(mirror, fm[name]):
            props.append(name)
    ir, im = images(retail, 8, BANKS["retail"]), images(mirror, 4, BANKS["mirror"])
    pictures = [i for i in range(IMAGES) if ir[i] != im[i]]
    lines = ["/* Generated by tools/gevr_mirror_lists.py from the retail and Mirror Mode",
             " * cartridges: the object models and images Wreck's Mirror Mode changed. */",
             "#define GEVR_MIRROR_PROPS %d" % len(props),
             "#define GEVR_MIRROR_IMAGES %d" % len(pictures),
             "#ifdef GEVR_MIRROR_PROP"]
    lines += ['GEVR_MIRROR_PROP("%s")' % p for p in props]
    lines += ["#endif", "#ifdef GEVR_MIRROR_IMAGE"]
    lines += ["GEVR_MIRROR_IMAGE(%d)" % i for i in pictures]
    lines += ["#endif", ""]
    Path(a.out).write_bytes("\n".join(lines).encode())
    print("%d props, %d images -> %s" % (len(props), len(pictures), a.out))


if __name__ == "__main__":
    sys.exit(main())
